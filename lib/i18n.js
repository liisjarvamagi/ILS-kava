// Kuupäevavahemik kujul "16.07–19.07.2026"
export function fmtDayRange(startsOn, endsOn) {
  if (!startsOn || !endsOn) return '';
  const dm = (d) => `${d.slice(8, 10)}.${d.slice(5, 7)}`;
  return `${dm(startsOn)}–${dm(endsOn)}.${endsOn.slice(0, 4)}`;
}

